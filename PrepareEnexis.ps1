$ErrorActionPreference = 'Stop'
$vendor = Join-Path $PSScriptRoot 'vendor\AutoCAD-Enexis-kabels-checker'
$source = Join-Path $vendor 'src\Enexis.KabelChecker.AutoCAD\Plugin.cs'
if (!(Test-Path -LiteralPath $source)) { throw 'De gepinde kabelchecker-bronnen ontbreken onder vendor/AutoCAD-Enexis-kabels-checker.' }
$text = [IO.File]::ReadAllText($source)
$marker = 'internal sealed record SelectionReadResult('
$index = $text.IndexOf($marker, [StringComparison]::Ordinal)
if ($index -lt 0) { throw 'De upstream selectielezer is gewijzigd; controleer de integratie.' }
# Only the independent selection helpers are copied. Upstream entry points and
# its separate-window manager must not register another plugin in the bundle.
$header = @'
// Selection helpers from pinned upstream Plugin.cs. Generated by PrepareEnexis.ps1.
using System.Text.RegularExpressions;
using Autodesk.AutoCAD.ApplicationServices;
using Autodesk.AutoCAD.DatabaseServices;
using Autodesk.AutoCAD.EditorInput;
using Autodesk.AutoCAD.Geometry;
using Enexis.KabelChecker.Core;
using AcApp = Autodesk.AutoCAD.ApplicationServices.Application;
namespace Enexis.KabelChecker.AutoCAD;

'@
$generated = Join-Path $PSScriptRoot 'src\Generated'
New-Item -ItemType Directory -Path $generated -Force | Out-Null
[IO.File]::WriteAllText((Join-Path $generated 'EnexisSelectionReader.cs'), $header + [Environment]::NewLine + $text.Substring($index))
$buttons = [IO.File]::ReadAllText((Join-Path $vendor 'src\Enexis.KabelChecker.AutoCAD\DeleteAllDirectionsButtonInstaller.cs'))
$start = $buttons.IndexOf('    [ModuleInitializer]', [StringComparison]::Ordinal)
$method = $buttons.IndexOf('    private static void AttachToOpenForms()', [StringComparison]::Ordinal)
$loop = 'foreach (var form in Application.OpenForms.Cast<Form>().OfType<KabelCheckerForm>().ToArray())'
if ($start -lt 0 -or $method -lt $start -or !$buttons.Contains($loop)) { throw 'Upstream knop-installatie is gewijzigd; controleer de integratie.' }
$buttons = $buttons.Substring(0, $start) + $buttons.Substring($method)
$buttons = $buttons.Replace('private static void AttachToOpenForms()', 'internal static void AttachToForms(IEnumerable<KabelCheckerForm> forms)').Replace($loop, 'foreach (var form in forms)')
[IO.File]::WriteAllText((Join-Path $generated 'EnexisButtonInstaller.cs'), '// Upstream button logic with explicit attachment for the embedded form.' + [Environment]::NewLine + $buttons)
$form = [IO.File]::ReadAllText((Join-Path $vendor 'src\Enexis.KabelChecker.AutoCAD\KabelCheckerFormV2.cs'))
$formDeclaration = 'internal sealed class KabelCheckerForm : Form'
if (!$form.Contains($formDeclaration)) { throw 'Upstream formulierdeclaratie is gewijzigd; controleer de adapter.' }
[IO.File]::WriteAllText((Join-Path $generated 'EnexisKabelCheckerForm.cs'), $form.Replace($formDeclaration, 'internal sealed partial class KabelCheckerForm : Form'))
$files = Get-ChildItem -LiteralPath (Join-Path $vendor 'src') -Recurse -File | Where-Object { $_.Extension -in @('.cs','.xlsx','.csproj') -and $_.FullName -notmatch '[\\/](bin|obj)[\\/]' }
$hashes = $files | ForEach-Object { [pscustomobject]@{ Path = $_.FullName.Substring($vendor.Length + 1).Replace('\','/'); SHA256 = (Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash } }
[pscustomobject]@{
    Repository = 'https://github.com/LukaStuurman/AutoCAD-Enexis-kabels-checker'
    Commit = '4009601e15fa4b1b6926380395132b0c1630ce21'
    Source = 'Pinned main, 9 October 2026'
    Files = $hashes
} | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath (Join-Path $PSScriptRoot 'enexis-source.json') -Encoding UTF8
